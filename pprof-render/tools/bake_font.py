#!/usr/bin/env python3
"""Bake Commit Mono into a fixed-cell 8-bit coverage LUT (build-time only).

Usage: bake_font.py FONT.woff OUT.js [px ...]

Layout per size: glyph g occupies bytes [g*w*h, (g+1)*w*h), row-major,
one byte of coverage (0..255, linear) per pixel. Glyphs 0..94 are ASCII
0x20..0x7E (index = codepoint - 0x20); EXTRA follow; the last glyph is the
replacement for anything unmapped.

Sizes should be multiples of 5: the advance is 600/1000 em, so only those
give an integer cell width (no accumulated spacing error, no hinting needed).
"""
import base64, io, sys
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

EXTRA = [0x2026, 0x00B7, 0x00D7, 0x2192]   # … · × →
REPLACEMENT = 0xFFFD

def main(src, out, sizes):
    tt = TTFont(src)
    upm, hhea = tt["head"].unitsPerEm, tt["hhea"]
    adv = tt["hmtx"][tt.getBestCmap()[0x4D]][0]
    version = next(str(n) for n in tt["name"].names if n.nameID == 5)
    buf = io.BytesIO(); tt.flavor = None; tt.save(buf)
    cps = list(range(0x20, 0x7F)) + EXTRA + [REPLACEMENT]
    entries = []
    for px in sizes:
        if (adv * px) % upm:
            sys.exit(f"{px}px: advance {adv*px/upm}px is not an integer")
        w = adv * px // upm
        asc = -(-hhea.ascent * px // upm)             # ceil
        h = asc + -(hhea.descent * px // upm)         # + ceil(|descent|)
        buf.seek(0)
        font = ImageFont.truetype(buf, px, layout_engine=ImageFont.Layout.BASIC)
        data, clipped = bytearray(), []
        for cp in cps:
            # Render on a padded canvas to detect ink escaping the cell.
            pad = Image.new("L", (w * 3, h * 3), 0)
            ImageDraw.Draw(pad).text((w, h + asc), chr(cp), font=font, fill=255, anchor="ls")
            cell = pad.crop((w, h, 2 * w, 2 * h))
            if sum(pad.tobytes()) != sum(cell.tobytes()):
                clipped.append(chr(cp))
            data += cell.tobytes()
        assert len(data) == len(cps) * w * h
        if clipped:
            print(f"  {px}px: ink clipped at cell edge for {''.join(clipped)!r}", file=sys.stderr)
        entries.append((px, w, h, asc, bytes(data)))
        print(f"  {px}px: cell {w}x{h}, baseline {asc}, {len(data)} bytes", file=sys.stderr)

    with open(out, "w") as f:
        f.write("// GENERATED by tools/bake_font.py -- do not edit.\n")
        f.write(f"// Commit Mono 400, {version}. SIL OFL 1.1, see third_party/commit-mono/LICENSE.\n")
        f.write("// Coverage LUT: glyph g at [g*w*h, (g+1)*w*h), row-major, 1 byte/pixel.\n\n")
        f.write("const b64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));\n\n")
        f.write(f"export const FIRST = 0x20;\nexport const ASCII_COUNT = 95;\n")
        f.write(f"export const EXTRA = {EXTRA!r};\n")
        f.write(f"export const REPLACEMENT_GLYPH = {len(cps) - 1};\n")
        f.write(f"export const GLYPH_COUNT = {len(cps)};\n\n")
        f.write("/** Codepoint -> glyph index. Total: unmapped input yields the replacement glyph. */\n")
        f.write("export const glyphIndex = (cp) => {\n")
        f.write("  if (cp >= FIRST && cp < FIRST + ASCII_COUNT) return cp - FIRST;\n")
        f.write("  const i = EXTRA.indexOf(cp);\n")
        f.write("  return i < 0 ? REPLACEMENT_GLYPH : ASCII_COUNT + i;\n};\n\n")
        f.write("export const FONTS = {\n")
        for px, w, h, asc, data in entries:
            f.write(f"  {px}: {{ px: {px}, w: {w}, h: {h}, baseline: {asc}, data: b64(\n")
            s = base64.b64encode(data).decode()
            for i in range(0, len(s), 100):
                f.write(f'    "{s[i:i+100]}"{" +" if i + 100 < len(s) else ""}\n')
            f.write("  ) },\n")
        f.write("};\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], [int(a) for a in sys.argv[3:]] or [10, 15, 20])
