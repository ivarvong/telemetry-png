#!/usr/bin/env python3
"""Bake Commit Mono (SIL OFL 1.1) into a run-length packed coverage atlas for otel-png.

Dev-time only: the output, otel-png-font.mjs, is plain data with no runtime deps.
usage: build-font.py <dir with CommitMono-400-Regular.otf, CommitMono-700-Regular.otf> <out.mjs>

The cell is 8 x 17 logical pixels (advance 0.6 em at 13.33 px), baked at 1x and 2x.
"""
import base64, json, sys
from PIL import Image, ImageDraw, ImageFont

src, out = sys.argv[1], sys.argv[2]
ASCII = ''.join(chr(c) for c in range(32, 127))
LATIN1 = ''.join(chr(c) for c in range(161, 256) if c != 173)
EXTRA = '…·→←µ–—'
CELL_W, CELL_H, ASCENT, PX = 8, 17, 14, 40 / 3
FACES = [('body', 'CommitMono-400-Regular.otf', ASCII + LATIN1 + EXTRA), ('bold', 'CommitMono-700-Regular.otf', ASCII)]

meta, blob = {}, bytearray()
for scale in (1, 2):
    meta[scale] = {}
    for name, file, chars in FACES:
        font = ImageFont.truetype(f'{src}/{file}', PX * scale)
        assert abs(font.getlength('0') - CELL_W * scale) < 1e-6
        chars = ''.join(dict.fromkeys(chars))
        w, h = CELL_W * scale, CELL_H * scale
        meta[scale][name] = dict(w=w, h=h, chars=chars, off=len(blob))
        for ch in chars:
            cell = Image.new('L', (w, h), 0)
            ImageDraw.Draw(cell).text((0, ASCENT * scale), ch, font=font, fill=255, anchor='ls')
            blob += bytes((v + 8) // 17 for v in cell.tobytes())  # 8-bit coverage -> 0..15

rle = bytearray()  # each byte: (coverage << 4) | (run - 1)
i = 0
while i < len(blob):
    j = i
    while j < len(blob) and j - i < 16 and blob[j] == blob[i]:
        j += 1
    rle.append((blob[i] << 4) | (j - i - 1))
    i = j
with open(out, 'w') as f:
    f.write('// Generated by tools/build-font.py. Commit Mono by Eigil Nikolajsen, SIL Open Font License 1.1.\n')
    f.write('// Coverage 0..15 per pixel, glyph cells concatenated, run-length packed, base64.\n')
    f.write(f'export const FONT_CELL = {{ w: {CELL_W}, h: {CELL_H} }}; // logical pixels\n')
    f.write(f'export const FONT_META = {json.dumps(meta, ensure_ascii=False)};\n')
    f.write(f'export const FONT_BYTES = {len(blob)};\n')
    f.write(f"export const FONT_RLE_B64 =\n  '{base64.b64encode(bytes(rle)).decode()}';\n")
print('raw', len(blob), 'rle', len(rle))
